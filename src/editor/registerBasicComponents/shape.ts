import { componentRegistry, lazy } from "../registryCore";
import {
  SHAPE_KIND_OPTIONS,
  DECOR_BORDER_STYLE_OPTIONS,
  DECOR_GRADIENT_DIRECTIONS,
  DECOR_LINECAP_OPTIONS,
  DECOR_LINEJOIN_OPTIONS,
  DECOR_SHADOW_OPTIONS,
  decorSupportsLineCap,
  decorSupportsLineJoin,
} from "../data/decorationShape";

export function registerShape(): void {
  componentRegistry.register({
    type: "shape",
    name: "形状",
    icon: "crop_square",
    description: "基础形状：矩形/圆形/椭圆/线条/三角/菱形/星形/多边形/十字/虚线框，支持渐变填充、描边细节、透明度与阴影",
    category: "ccat_shape",
    version: "2.0.0",
    builtIn: true,
    enabled: true,
    defaultSize: { width: 200, height: 150 },
    minSize: { width: 20, height: 12 },
    defaultConfig: {
      shapeType: "rect",
      fill: "rgba(33, 150, 243, 0.3)",
      gradientEnabled: false,
      gradientFrom: "#2196F3",
      gradientTo: "#FF9800",
      gradientDirection: "to-right",
      stroke: "#2196F3",
      strokeWidth: 2,
      borderStyle: "solid",
      borderRadius: 0,
      sides: 6,
      points: 5,
      innerRatio: 0.4,
      thickness: 10,
      lineDirection: "horizontal",
      dashLength: 8,
      gapLength: 4,
      /* 空串 = 跟随所选形状的历史默认（线条=圆头、虚线框=平头…），见 `decorLineCapOf` */
      lineCap: "",
      lineJoin: "",
      opacity: 1,
      shadow: "none",
    },
    capabilities: {
      resizable: true,
      rotatable: true,
      draggable: true,
      connectable: false,
      embeddable: false,
    },
    renderer: lazy(() => import("../renderers/ShapeRenderer").then(m => ({ default: m.ShapeRenderer }))),
    configSchema: [
      { key: "shapeType", label: "形状类型", type: "select", options: SHAPE_KIND_OPTIONS, group: "内容",
        help: "几何与装饰组件组共用同一份实现：同名形状在两组里画出来完全一致" },
      { key: "sides", label: "边数", type: "number", min: 3, max: 24, group: "内容",
        hidden: (c) => c.shapeType !== "polygon", help: "正多边形的边数" },
      { key: "points", label: "角数", type: "number", min: 3, max: 12, group: "内容",
        hidden: (c) => c.shapeType !== "star", help: "星形的角数" },
      { key: "innerRatio", label: "内径比", type: "number", min: 0.1, max: 0.9, step: 0.05, group: "内容",
        hidden: (c) => c.shapeType !== "star", help: "内顶点与外顶点半径之比：越小越尖" },
      { key: "thickness", label: "笔画粗细", type: "number", min: 2, max: 60, group: "内容",
        hidden: (c) => c.shapeType !== "cross", help: "十字的臂宽" },
      { key: "lineDirection", label: "线条方向", type: "select", group: "内容",
        hidden: (c) => c.shapeType !== "line", options: [
          { label: "水平", value: "horizontal" },
          { label: "垂直", value: "vertical" },
          { label: "左上-右下", value: "diagonal-tl-br" },
          { label: "右上-左下", value: "diagonal-tr-bl" },
        ] },
      { key: "dashLength", label: "虚线段长", type: "number", min: 1, max: 40, group: "内容",
        hidden: (c) => c.shapeType !== "dashed-box" },
      { key: "gapLength", label: "虚线间隔", type: "number", min: 1, max: 40, group: "内容",
        hidden: (c) => c.shapeType !== "dashed-box" },

      { key: "gradientEnabled", label: "渐变填充", type: "toggle", group: "填充",
        help: "开启后用渐变替代纯色填充（圆形/线条/十字以外均支持）" },
      { key: "fill", label: "填充色", type: "color", group: "填充", hidden: (c) => c.gradientEnabled === true },
      { key: "gradientFrom", label: "渐变起始色", type: "color", group: "填充", hidden: (c) => c.gradientEnabled !== true },
      { key: "gradientTo", label: "渐变终止色", type: "color", group: "填充", hidden: (c) => c.gradientEnabled !== true },
      { key: "gradientDirection", label: "渐变方向", type: "select", group: "填充", hidden: (c) => c.gradientEnabled !== true,
        options: DECOR_GRADIENT_DIRECTIONS },

      { key: "stroke", label: "描边色", type: "color", group: "描边", hidden: (c) => c.borderStyle === "none" },
      { key: "strokeWidth", label: "描边粗细", type: "number", min: 0, max: 30, group: "描边", hidden: (c) => c.borderStyle === "none" },
      { key: "borderStyle", label: "描边样式", type: "select", group: "描边", options: DECOR_BORDER_STYLE_OPTIONS,
        help: "线条形状下等价于线型" },
      /* 端点/转折样式：几何与装饰组共用一份，能力判据也共用（`shapeType` → 装饰形状名）。
         空串 = 跟随该形状的历史默认，因此这里多一档「跟随形状默认」而不是假装有个固定默认值。 */
      { key: "lineCap", label: "端点样式", type: "select", group: "描边",
        hidden: (c) => !decorSupportsLineCap("decoration-" + String(c.shapeType || "rect")),
        options: [{ label: "跟随形状默认", value: "" }, ...DECOR_LINECAP_OPTIONS] },
      { key: "lineJoin", label: "转折样式", type: "select", group: "描边",
        hidden: (c) => !decorSupportsLineJoin("decoration-" + String(c.shapeType || "rect")),
        options: [{ label: "跟随形状默认", value: "" }, ...DECOR_LINEJOIN_OPTIONS] },
      { key: "borderRadius", label: "圆角", type: "number", min: 0, max: 80, group: "描边",
        hidden: (c) => !["rect", "dashed-box"].includes(String(c.shapeType)) && c.gradientEnabled !== true,
        help: "矩形/虚线框/渐变块的圆角(px)" },

      { key: "opacity", label: "透明度", type: "slider", min: 0, max: 1, step: 0.05, group: "效果" },
      { key: "shadow", label: "阴影", type: "select", group: "效果", options: DECOR_SHADOW_OPTIONS,
        help: "按形状轮廓投射（drop-shadow，镂空形状不会变成方块阴影）" },
    ],
  });
}
