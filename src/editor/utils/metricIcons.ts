/** 归一化图标名：小写 + 中划线/空格 → 下划线 */
export function normalizeIconName(name: string): string {
  return String(name || "")
    .trim()
    .toLowerCase()
    .replace(/[\s-]+/g, "_");
}

/** 支持的所有指标图标名（供可视化选择器遍历） */
export const METRIC_ICON_NAMES: string[] = Object.keys(ICON_PATHS);

/** 是否支持该图标名 */
export function hasMetricIcon(name: string): boolean {
  return normalizeIconName(name) in ICON_PATHS;
}

/** 安全转义颜色值（禁止注入引号/尖括号） */
function safeColor(color: string): string {
  return String(color || "")
    .replace(/[<>"']/g, "")
    .slice(0, 64);
}

/**
 * 生成 Lucide 风格内联 SVG（stroke 线条，24 坐标系）
 * @param name 图标名（如 trending_up）；未知返回 ""
 * @param size 宽高 px
 * @param color 线条颜色（自动安全转义）
 * @param strokeWidth 线宽（默认 2，细线条可用 1.5）
 */
export function buildMetricIconSvg(name: string, size: number, color: string, strokeWidth = 2): string {
  const inner = ICON_PATHS[normalizeIconName(name)];
  if (!inner) return "";
  const sz = Math.max(8, Math.round(size));
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${sz}" height="${sz}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="${safeColor(color)}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">` +
    inner +
    `</svg>`
  );
}