import { componentRegistry, lazy } from "../registryCore";
import { dataSourceSchemaFieldsNoStatic } from "../dataSourceFields";
import { diagnoseCascaderOptions, diagnoseCascaderPath, parseCascaderValue, cascaderPathOptions } from "../data/cascaderOptions";
import { fieldScaleFitField, isLocalApiHiddenLocal, validationSchema } from "./shared";

// ─── 级联选择 ───
export function registerFormCascader(): void {
  componentRegistry.register({
    type: "form-cascader",
    name: "级联选择",
    icon: "account_tree",
    description: "多级联动下拉选择器，支持省市区等树形数据，可静态可接口（含认证接入）",
    category: "ccat_form",
    version: "1.0.0",
    builtIn: true,
    enabled: true,
    defaultSize: { width: 280, height: 56 },
    minSize: { width: 160, height: 40 },
    defaultConfig: {
      fieldName: "",
      label: "所在地区",
      options: "",
      value: [],
      placeholder: "请选择地区",
      labelPlacement: "inside",
      showPath: true,
      separator: " / ",
      submitMode: "leaf",
      clearable: false,
      required: false,
      helperText: "",
      disabled: false,
      bgColor: "#ffffff",
      textColor: "#333333",
      borderColor: "#d0d0d8",
      borderWidth: 1,
      focusBorderColor: "#1976d2",
      borderRadius: 4,
      accentColor: "#1976d2",
      fontSize: 14,
      fontWeight: "normal",
      labelColor: "",
      labelFontSize: 0,
      labelBgColor: "",
      labelRadius: 4,
      labelGap: 4,
    },
    capabilities: {
      resizable: true, rotatable: false, draggable: true, connectable: false, embeddable: false,
    },
    renderer: lazy(() => import("../renderers/CascaderRenderer").then(m => ({ default: m.CascaderRenderer }))),
    configSchema: [
      { key: "fieldName", label: "字段名", type: "text", group: "内容", placeholder: "如 region，留空用标签", help: "提交到接口时的字段 key" },
      { key: "label", label: "标签", type: "text", group: "内容" },
      { key: "placeholder", label: "占位/未选提示", type: "text", group: "内容" },
      { key: "labelPlacement", label: "标签位置", type: "select", group: "内容", options: [
        { label: "内置悬浮", value: "inside" },
        { label: "外部上方", value: "top" },
        { label: "无标签", value: "none" },
      ] },
      { key: "options", label: "选项数据", type: "cascader-options", group: "内容",
        hidden: (c) => (c.dataMode ?? "static") === "api",
        diagnose: (c) => diagnoseCascaderOptions(c.options),
        help: "逐条编辑显示名与提交值，「添加下级选项」构成层级；旧的 JSON/逐行文本会自动解析进面板" },
      { key: "value", label: "默认选中路径", type: "select", group: "内容",
        placeholder: "从列表里选，或直接输入路径",
        // 候选 = 当前选项树里的全部合法路径（选就不容易拼错）；editable 保留手输（接口模式 / 数据未填时必须能写）
        dynamicOptions: (c) => cascaderPathOptions(c.options),
        editable: true,
        diagnose: (c) => ((c.dataMode ?? "static") === "api"
          ? (parseCascaderValue(c.value).length
            ? { level: "info" as const, text: "接口模式：此路径在运行时按接口返回的树解析，这里不做校验" }
            : null)
          : diagnoseCascaderPath(c.value, c.options)),
        help: "各级提交值用 / 分隔（也接受 JSON 数组）；留空则不预选任何项" },
      { key: "showPath", label: "显示完整路径", type: "toggle", group: "内容", help: "关闭则只显示末级名称" },
      { key: "separator", label: "路径分隔符", type: "text", group: "内容",
        hidden: (c) => c.showPath === false && c.submitMode !== "path" && c.submitMode !== "labelPath",
        help: "既用于触发器上的路径显示，也用于「提交值」选完整路径时的拼接（如 / 、- 、>）" },
      { key: "submitMode", label: "提交值", type: "select", group: "内容", options: [
        { label: "末级提交值", value: "leaf" },
        { label: "完整路径(取值)", value: "path" },
        { label: "完整路径(显示名)", value: "labelPath" },
      ], help: "表单提交时写入的取值口径：末级值 / 各级提交值以分隔符相连 / 各级显示名以分隔符相连" },
      { key: "clearable", label: "一键清空", type: "toggle", group: "内容" },
      { key: "required", label: "必填", type: "toggle", group: "内容" },
      { key: "helperText", label: "帮助文字", type: "text", group: "内容", help: "控件下方常驻说明文字，校验出错时让位" },
      ...dataSourceSchemaFieldsNoStatic,
      { key: "apiValueField", label: "取值字段", type: "text", group: "数据源", hidden: isLocalApiHiddenLocal,
        placeholder: "如 code", help: "接口返回对象的取值字段；留空依次回退 value → id" },
      { key: "apiLabelField", label: "显示字段", type: "text", group: "数据源", hidden: isLocalApiHiddenLocal,
        placeholder: "如 name", help: "接口返回对象的显示字段；留空依次回退 label → name → text" },
      { key: "apiChildrenField", label: "子级字段", type: "text", group: "数据源", hidden: isLocalApiHiddenLocal,
        placeholder: "如 children", help: "接口返回对象的下级数组字段；留空依次回退 children → items" },
      ...validationSchema,
      { key: "disabled", label: "禁用", type: "toggle", group: "状态" },
      { key: "bgColor", label: "背景色", type: "color", group: "样式" },
      { key: "textColor", label: "文字颜色", type: "color", group: "样式" },
      { key: "borderColor", label: "边框颜色", type: "color", group: "样式" },
      { key: "borderWidth", label: "边框粗细", type: "number", min: 1, max: 8, group: "样式" },
      { key: "focusBorderColor", label: "聚焦边框色", type: "color", group: "样式" },
      { key: "borderRadius", label: "圆角", type: "number", min: 0, max: 40, group: "样式" },
      { key: "accentColor", label: "选项强调色", type: "color", group: "样式", help: "展开面板中选中/悬浮项的背景色" },
      { key: "fontSize", label: "字号", type: "number", min: 10, max: 30, group: "样式" },
      { key: "fontWeight", label: "文字字重", type: "select", group: "样式", options: [
        { label: "常规", value: "normal" },
        { label: "中等", value: "500" },
        { label: "加粗", value: "bold" },
      ] },
      { key: "labelColor", label: "标签颜色", type: "color", group: "样式", help: "留空跟随控件文字色" },
      { key: "labelFontSize", label: "标签字号", type: "number", min: 0, max: 30, group: "样式", help: "0 或留空表示跟随控件字号" },
      { key: "labelBgColor", label: "标签背景色", type: "color", group: "样式", help: "内置悬浮标签底色；留空跟随控件背景色形成无缝缺口" },
      { key: "labelRadius", label: "标签背景圆角", type: "number", min: 0, max: 40, group: "样式" },
      { key: "labelGap", label: "标签间距", type: "number", min: 0, max: 24, group: "样式", hidden: (c) => c.labelPlacement !== "top", help: "仅「外部上方」标签位置生效" },
      // 字段型「文字随框缩放」开关（与 input/select/date 等 8 个字段型控件同款；默认关零回归）
      fieldScaleFitField,
    ],
  });
}
